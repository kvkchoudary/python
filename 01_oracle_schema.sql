-- Oracle 19c+ configuration table for scheduled Spark exports.
CREATE TABLE SPARK_EXPORT_CONFIG (
 CONFIG_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 CONSUMER_NAME VARCHAR2(128) NOT NULL,
 HIERARCHY_PATH VARCHAR2(512) NOT NULL,
 DATA_TYPE VARCHAR2(128) NOT NULL,
 SOURCE_HDFS_PATH VARCHAR2(2000),
 SPARK_SQL CLOB,
 FID VARCHAR2(256) NOT NULL,
 TARGET_S3_PATH VARCHAR2(2000) NOT NULL,
 OUTPUT_FORMAT VARCHAR2(16) NOT NULL,
 WRITE_MODE VARCHAR2(16) DEFAULT 'OVERWRITE' NOT NULL,
 REGISTER_HIVE_TABLE CHAR(1) DEFAULT 'N' NOT NULL,
 HIVE_DATABASE VARCHAR2(128),
 HIVE_TABLE VARCHAR2(128),
 -- CSV/JSON must have an explicit schema for registration. JSON Spark StructType JSON format.
 SCHEMA_JSON CLOB,
 -- Partition columns used by Spark SQL writer, comma-separated. Not used by copy flow.
 PARTITION_COLUMNS VARCHAR2(1000),
 IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
 CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT CK_SEC_ACTIVE CHECK (IS_ACTIVE IN ('Y','N')),
 CONSTRAINT CK_SEC_REGISTER CHECK (REGISTER_HIVE_TABLE IN ('Y','N')),
 CONSTRAINT CK_SEC_FORMAT CHECK (OUTPUT_FORMAT IN ('PARQUET','AVRO','CSV','JSON')),
 CONSTRAINT CK_SEC_MODE CHECK (WRITE_MODE IN ('APPEND','OVERWRITE')),
 -- SPARK_SQL is CLOB; source XOR validation is performed in Python.
 CONSTRAINT CK_SEC_HIVE CHECK (REGISTER_HIVE_TABLE = 'N' OR
   (HIVE_DATABASE IS NOT NULL AND HIVE_TABLE IS NOT NULL)),
 CONSTRAINT UQ_SEC_KEY UNIQUE (CONSUMER_NAME,HIERARCHY_PATH,DATA_TYPE)
);
COMMENT ON TABLE SPARK_EXPORT_CONFIG IS 'One configuration per consumer/hierarchy/data type; inactive records may be reactivated.';
